-- Bombim00 durable data store.
-- Apply with Supabase CLI: supabase db push
create extension if not exists pgcrypto;

create table if not exists public.lottery_results (
  id bigint generated by default as identity primary key,
  fingerprint text not null unique,
  lottery_name text,
  category text,
  draw_date text,
  notification_status text,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists lottery_results_draw_date_idx on public.lottery_results (draw_date);
create index if not exists lottery_results_lottery_name_idx on public.lottery_results (lottery_name);

create table if not exists public.lottery_catalog (
  lottery_id text primary key,
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  id text primary key default 'main' check (id = 'main'),
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.system_status (
  id text primary key default 'main' check (id = 'main'),
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.self_healing_history (
  id text primary key default 'main' check (id = 'main'),
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

-- This table records future delivery events. The importer deliberately does not
-- invent historical channel/provider events from the legacy "sent" flag.
create table if not exists public.notification_events (
  id uuid primary key default gen_random_uuid(),
  fingerprint text not null,
  channel text not null,
  delivery_status text not null,
  provider_reference text,
  payload jsonb not null default '{}'::jsonb,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notification_events_fingerprint_idx
  on public.notification_events (fingerprint);

create table if not exists public.legacy_import_batches (
  source_sha256 text primary key,
  imported_at timestamptz not null default now(),
  results_count integer not null,
  catalog_count integer not null,
  history_count integer not null
);

-- Atomic, repeatable import. Upserts existing identities and never deletes rows.
create or replace function public.import_bombim00_legacy_snapshot(
  p_snapshot jsonb,
  p_source_sha256 text
) returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_result jsonb;
  v_item jsonb;
  v_results_count integer := 0;
  v_catalog_count integer := 0;
  v_history_count integer := 0;
begin
  if p_snapshot is null or jsonb_typeof(p_snapshot) <> 'object' then
    raise exception 'snapshot must be a JSON object';
  end if;
  if p_source_sha256 !~ '^[a-f0-9]{64}$' then
    raise exception 'source_sha256 must be a lowercase SHA-256 digest';
  end if;
  if jsonb_typeof(p_snapshot->'results') <> 'array'
     or jsonb_typeof(p_snapshot->'catalog') <> 'array'
     or jsonb_typeof(p_snapshot->'self_healing_history') <> 'array' then
    raise exception 'snapshot arrays are missing or invalid';
  end if;

  for v_item in select value from jsonb_array_elements(p_snapshot->'results')
  loop
    if coalesce(v_item->>'fingerprint', '') = '' or jsonb_typeof(v_item->'payload') <> 'object' then
      raise exception 'invalid lottery result row';
    end if;
    insert into public.lottery_results
      (fingerprint, lottery_name, category, draw_date, notification_status, payload, updated_at)
    values
      (v_item->>'fingerprint',
       coalesce(v_item->'payload'->>'ชื่อหวย', v_item->'payload'->>'หวย', v_item->'payload'->>'lottery_name'),
       coalesce(v_item->'payload'->>'หมวดหวย', v_item->'payload'->>'category'),
       coalesce(v_item->'payload'->>'งวดวันที่', v_item->'payload'->>'วันที่จัดรูปแบบ', v_item->'payload'->>'draw_date'),
       v_item->'payload'->>'สถานะการแจ้งเตือน',
       v_item->'payload', now())
    on conflict (fingerprint) do update set
      lottery_name = excluded.lottery_name,
      category = excluded.category,
      draw_date = excluded.draw_date,
      notification_status = excluded.notification_status,
      payload = excluded.payload,
      updated_at = now();
    v_results_count := v_results_count + 1;
  end loop;

  for v_item in select value from jsonb_array_elements(p_snapshot->'catalog')
  loop
    if coalesce(v_item->>'id', '') = '' then raise exception 'catalog row has no id'; end if;
    insert into public.lottery_catalog (lottery_id, payload, updated_at)
    values (v_item->>'id', v_item, now())
    on conflict (lottery_id) do update set payload = excluded.payload, updated_at = now();
    v_catalog_count := v_catalog_count + 1;
  end loop;

  if jsonb_typeof(p_snapshot->'settings') <> 'object'
     or jsonb_typeof(p_snapshot->'status') <> 'object' then
    raise exception 'settings or status object is missing';
  end if;
  insert into public.app_settings (id, payload, updated_at)
  values ('main', p_snapshot->'settings', now())
  on conflict (id) do update set payload = excluded.payload, updated_at = now();

  insert into public.system_status (id, payload, updated_at)
  values ('main', p_snapshot->'status', now())
  on conflict (id) do update set payload = excluded.payload, updated_at = now();

  insert into public.self_healing_history (id, payload, updated_at)
  values ('main', p_snapshot->'self_healing_history', now())
  on conflict (id) do update set payload = excluded.payload, updated_at = now();

  v_history_count := jsonb_array_length(p_snapshot->'self_healing_history');

  insert into public.legacy_import_batches
    (source_sha256, results_count, catalog_count, history_count)
  values (p_source_sha256, v_results_count, v_catalog_count, v_history_count)
  on conflict (source_sha256) do update set
    imported_at = now(),
    results_count = excluded.results_count,
    catalog_count = excluded.catalog_count,
    history_count = excluded.history_count;

  return jsonb_build_object(
    'source_sha256', p_source_sha256,
    'results_count', v_results_count,
    'catalog_count', v_catalog_count,
    'history_count', v_history_count,
    'status', 'imported'
  );
end;
$$;

-- No browser role may invoke the bulk-import RPC or read/write raw tables directly.
alter table public.lottery_results enable row level security;
alter table public.lottery_catalog enable row level security;
alter table public.app_settings enable row level security;
alter table public.system_status enable row level security;
alter table public.self_healing_history enable row level security;
alter table public.notification_events enable row level security;
alter table public.legacy_import_batches enable row level security;

revoke all on public.lottery_results, public.lottery_catalog, public.app_settings,
  public.system_status, public.self_healing_history, public.notification_events,
  public.legacy_import_batches from anon, authenticated;
revoke all on function public.import_bombim00_legacy_snapshot(jsonb, text) from public, anon, authenticated;
grant execute on function public.import_bombim00_legacy_snapshot(jsonb, text) to service_role;
